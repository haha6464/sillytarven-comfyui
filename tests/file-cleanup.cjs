const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { run } = require('../server/index.cjs');
(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'scene-draw-cleanup-test-'));
  const dirs = { root, userImages: path.join(root,'user/images'), chats: path.join(root,'chats'), groupChats:path.join(root,'group chats') };
  for (const dir of [dirs.userImages, dirs.chats, dirs.groupChats]) await fs.mkdir(dir,{recursive:true});
  const shared = 'user/images/shared.png', orphan = 'user/images/unknown.png';
  await fs.writeFile(path.join(root,shared),'fixture');
  await fs.writeFile(path.join(root,orphan),'fixture');
  const first = path.join(dirs.chats,'a.jsonl'), second = path.join(dirs.groupChats,'b.jsonl');
  const contents = JSON.stringify({extra:{sceneDrawImage:shared}})+'\n';
  await fs.writeFile(first,contents); await fs.writeFile(second,contents);
  await run(dirs,'track');
  await fs.writeFile(first,'{}\n');
  let result = await run(dirs,'cleanup',[shared]);
  assert.equal(result.deleted.length,0);
  assert(result.retained.includes(shared),'Shared images survive');
  await fs.writeFile(second,'{}\n');
  result = await run(dirs,'report');
  assert(result.candidates.some(x=>x.path===shared));
  assert(result.unclassified.some(x=>x.path===orphan));
  await fs.stat(path.join(root,shared));
  result = await run(dirs,'cleanup');
  assert(result.deleted.includes(shared),'Deleting last chat releases registered file');
  await fs.stat(path.join(root,orphan));
  await fs.mkdir(path.join(dirs.userImages,'scene-draw'));
  const historic = 'user/images/scene-draw/historical.png';
  await fs.writeFile(path.join(root,historic),'fixture');
  await run(dirs,'track');
  result = await run(dirs,'cleanup');
  assert(!result.deleted.includes(historic),'Historical orphans are never automatically deleted on startup or cleanup');
  await fs.writeFile(first,'{broken\n');
  await assert.rejects(run(dirs,'cleanup',[historic]));
  await fs.stat(path.join(root,historic));
  await fs.writeFile(first,'{}\n');
  result = await run(dirs,'cleanup',['../../outside.png',historic]);
  assert.deepEqual(result.deleted,[historic]);
  console.log('File cleanup: real fixture unlink, shared references, deleted chats, report-only audit, historical ownership and parse-failure protection passed.');
  // Only this explicit test-owned temporary directory is removed.
  await fs.rm(root,{recursive:true});
})().catch(error=>{console.error(error);process.exitCode=1;});
